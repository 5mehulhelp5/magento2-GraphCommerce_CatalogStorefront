<?php
declare(strict_types=1);

namespace GraphCommerce\CatalogStorefrontUrlRewrite\Test\Unit\Model\Document\Writer;

use GraphCommerce\CatalogStorefrontApi\Storage\MetadataDocumentStorageInterface;
use GraphCommerce\CatalogStorefrontUrlRewrite\Model\Collation;
use GraphCommerce\CatalogStorefrontUrlRewrite\Model\Document\Writer\UrlRewrites;
use GraphCommerce\CatalogStorefrontUrlRewrite\Model\ResourceModel\ColumnCollations;
use Magento\Store\Api\Data\StoreInterface;
use Magento\Store\Model\StoreManagerInterface;
use PHPUnit\Framework\TestCase;

class UrlRewritesTest extends TestCase
{
    /** @var array<int, array{0: string, 1: string, 2: array}> the upserts and deletes, in call order */
    private array $writes = [];

    private function writer(string $collation = 'utf8mb4_general_ci'): UrlRewrites
    {
        $this->writes = [];
        $storage = $this->createMock(MetadataDocumentStorageInterface::class);
        $storage->method('upsert')->willReturnCallback(function (string $entity, string $store, array $documents): void {
            $this->writes[] = ['upsert', $entity . '/' . $store, $documents];
        });
        $storage->method('delete')->willReturnCallback(function (string $entity, string $store, array $ids): void {
            $this->writes[] = ['delete', $entity . '/' . $store, $ids];
        });
        $collations = $this->createStub(ColumnCollations::class);
        $collations->method('byColumn')->willReturn([
            'url_rewrite_id' => null,
            'entity_type' => 'utf8mb4_general_ci',
            'entity_id' => null,
            'request_path' => $collation,
            'target_path' => 'utf8mb4_general_ci',
            'redirect_type' => null,
            'store_id' => null,
            'description' => 'utf8mb4_general_ci',
            'is_autogenerated' => null,
            'metadata' => 'utf8mb4_general_ci',
        ]);
        $stores = [];
        foreach (['default', 'second'] as $code) {
            $store = $this->createStub(StoreInterface::class);
            $store->method('getCode')->willReturn($code);
            $stores[] = $store;
        }
        $storeManager = $this->createStub(StoreManagerInterface::class);
        $storeManager->method('getStores')->willReturn($stores);

        return new UrlRewrites($storage, new Collation(array_combine(range(97, 122), range('A', 'Z'))), $collations, $storeManager);
    }

    public function testARowBecomesItsDocumentWithTheFoldedKeysAndEveryStoreViewGetsItsCollation(): void
    {
        $this->writer()->write([[
            'urlRewriteId' => '10',
            'storeViewCode' => 'default',
            'entityType' => 'category',
            'entityId' => '25',
            'requestPath' => 'women/Tops.html',
            'targetPath' => 'catalog/category/view/id/25',
            'redirectType' => '0',
            'storeId' => '1',
            'isAutogenerated' => '1',
        ]]);

        $collation = ['collation' => ['kind' => 'collation', 'collation' => 'utf8mb4_general_ci']];
        $this->assertSame([
            ['upsert', 'url_rewrite/default', [10 => [
                'url_rewrite_id' => '10',
                'entity_type' => 'category',
                'entity_id' => '25',
                'request_path' => 'women/Tops.html',
                'target_path' => 'catalog/category/view/id/25',
                'redirect_type' => '0',
                'store_id' => '1',
                'description' => null,
                'is_autogenerated' => '1',
                'metadata' => null,
                'category_id' => null,
                'product_id' => null,
                'entity_type_key' => 'CATEGORY',
                'request_path_key' => 'WOMEN/TOPS.HTML',
                'target_path_key' => 'CATALOG/CATEGORY/VIEW/ID/25',
                'description_key' => null,
                'metadata_key' => null,
            ]] + $collation],
            ['upsert', 'url_rewrite/second', $collation],
        ], $this->writes);
    }

    public function testADeletedRowDeletesItsDocument(): void
    {
        $this->writer()->write([['urlRewriteId' => '11', 'storeViewCode' => 'second', 'deleted' => true]]);

        $this->assertSame(['delete', 'url_rewrite/second', [11]], end($this->writes));
    }

    public function testACollationTheFoldDoesNotKnowStopsTheBatchBeforeItWrites(): void
    {
        $writer = $this->writer('utf8mb4_unicode_ci');

        try {
            $writer->write([['urlRewriteId' => '10', 'storeViewCode' => 'default']]);
            $this->fail('The batch was written');
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('url_rewrite.request_path uses the collation utf8mb4_unicode_ci', $e->getMessage());
        }
        $this->assertSame([], $this->writes);
    }

    public function testARowWithoutItsIdentityStopsTheBatch(): void
    {
        $this->expectException(\RuntimeException::class);

        $this->writer()->write([['urlRewriteId' => '10']]);
    }
}
