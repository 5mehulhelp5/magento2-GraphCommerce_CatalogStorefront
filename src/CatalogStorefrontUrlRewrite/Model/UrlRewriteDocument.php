<?php
declare(strict_types=1);

namespace GraphCommerce\CatalogStorefrontUrlRewrite\Model;

/**
 * The shape of a url rewrite document: one row of the url rewrite table in the index of the store
 * view of the row, keyed by its id, with the columns as the table gives them (strings or null), the
 * category and product id of its product category relation, and the folded key of every string
 * column. The document `collation` of each store view names the collation of the table: a store
 * view without it has no url rewrite documents.
 */
final class UrlRewriteDocument
{
    public const ENTITY = 'url_rewrite';

    /** The id and the kind of the document that names the collation of the store view's rows. */
    public const COLLATION = 'collation';

    public const KIND = 'kind';

    /** @var array<string, string> the feed field of each column of a row */
    public const COLUMNS = [
        'urlRewriteId' => 'url_rewrite_id',
        'entityType' => 'entity_type',
        'entityId' => 'entity_id',
        'requestPath' => 'request_path',
        'targetPath' => 'target_path',
        'redirectType' => 'redirect_type',
        'storeId' => 'store_id',
        'description' => 'description',
        'isAutogenerated' => 'is_autogenerated',
        'metadata' => 'metadata',
        'categoryId' => 'category_id',
        'productId' => 'product_id',
    ];

    /** The string columns of the table: a lookup compares them through the collation, by their folded key. */
    public const STRINGS = ['entity_type', 'request_path', 'target_path', 'description', 'metadata'];

    /** The integer columns of the table: a lookup compares them as numbers. */
    public const INTEGERS = ['url_rewrite_id', 'entity_id', 'redirect_type', 'store_id', 'is_autogenerated'];

    /** The columns of the product category relation. */
    public const RELATION = ['category_id', 'product_id'];

    public const KEY_SUFFIX = '_key';
}
