<?php
/**
 * Writes the weight map of the general_ci collations for
 * GraphCommerce\CatalogStorefrontUrlRewrite\Model\Collation from the database. Run from the
 * Magento root:
 *
 *     php app/code/GraphCommerce/CatalogStorefront/dev/url-rewrite/collation-map.php
 *
 * It asks the database for the utf8mb4_general_ci weight of every character of the basic
 * multilingual plane and writes the characters whose weight is another character to
 * src/CatalogStorefrontUrlRewrite/data/general_ci.php. It stops without writing when a weight is
 * not one character, when a character above the plane does not weigh U+FFFD, or when the
 * collation does not ignore trailing spaces: the fold assumes all three.
 */
declare(strict_types=1);

use Magento\Framework\App\Bootstrap;
use Magento\Framework\App\ResourceConnection;

require getcwd() . '/app/bootstrap.php';
$connection = Bootstrap::create(BP, $_SERVER)->getObjectManager()->get(ResourceConnection::class)->getConnection();
$target = dirname(__DIR__, 2) . '/src/CatalogStorefrontUrlRewrite/data/general_ci.php';
$weightOf = static fn(string $codePoint): string =>
    "HEX(WEIGHT_STRING(CONVERT(CHAR($codePoint USING utf32) USING utf8mb4) COLLATE utf8mb4_general_ci))";
$stop = static function (string $message): never {
    fwrite(STDERR, $message . "\n");
    exit(1);
};

if ((string)$connection->fetchOne('SELECT ' . $weightOf((string)0x1F600)) !== 'FFFD') {
    $stop('A character above the basic multilingual plane does not weigh U+FFFD.');
}
if ((string)$connection->fetchOne(
    "SELECT CONVERT('a' USING utf8mb4) COLLATE utf8mb4_general_ci = CONVERT('a  ' USING utf8mb4)"
) !== '1') {
    $stop('utf8mb4_general_ci does not ignore trailing spaces.');
}

$digit = 'SELECT 0 AS d UNION ALL SELECT ' . implode(' UNION ALL SELECT ', range(1, 15));
$weights = $connection->fetchPairs(
    "SELECT n, {$weightOf('n')} FROM ("
    . "SELECT a.d * 4096 + b.d * 256 + c.d * 16 + e.d AS n"
    . " FROM ($digit) a CROSS JOIN ($digit) b CROSS JOIN ($digit) c CROSS JOIN ($digit) e"
    . ') code_points WHERE n NOT BETWEEN ' . 0xD800 . ' AND ' . 0xDFFF . ' ORDER BY n'
);

$map = [];
foreach ($weights as $codePoint => $hex) {
    $parts = str_split((string)$hex, 4);
    if (count($parts) !== 1 || strlen($parts[0]) !== 4) {
        $stop(sprintf('U+%04X weighs %s, which is not one character.', $codePoint, $hex));
    }
    $weight = (int)hexdec($parts[0]);
    if ($weight >= 0xD800 && $weight <= 0xDFFF) {
        $stop(sprintf('U+%04X weighs the surrogate %s.', $codePoint, $hex));
    }
    if ($weight !== (int)$codePoint) {
        $map[(int)$codePoint] = mb_chr($weight, 'UTF-8');
    }
}

$lines = [
    '<?php',
    '// Generated by dev/url-rewrite/collation-map.php from ' . $connection->fetchOne('SELECT VERSION()') . ':',
    '// the characters whose utf8mb4_general_ci weight is another character, by code point.',
    'return [',
];
foreach ($map as $codePoint => $weight) {
    $lines[] = sprintf('    %d => %s,', $codePoint, var_export($weight, true));
}
$lines[] = '];';
if (!is_dir(dirname($target))) {
    mkdir(dirname($target), 0775, true);
}
file_put_contents($target, implode("\n", $lines) . "\n");
printf("%d of %d weights written to %s\n", count($map), count($weights), $target);
