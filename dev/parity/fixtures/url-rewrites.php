<?php
/**
 * The custom url rewrites of dev/parity/route-pages.txt in the default store view: the permanent
 * redirect gc-parity-redirect.html and the rewrite gc-parité.html, both to the first category of
 * the store view, so the gate sees a stored redirect and a request path the collation folds. Run
 * from the Magento root; the url rewrite feed exports them with the next cron run. Does nothing for
 * a request path that exists.
 */
declare(strict_types=1);

use Magento\Framework\App\Bootstrap;
use Magento\Framework\App\State;
use Magento\Store\Model\StoreManagerInterface;
use Magento\UrlRewrite\Model\ResourceModel\UrlRewrite as UrlRewriteResource;
use Magento\UrlRewrite\Model\UrlFinderInterface;
use Magento\UrlRewrite\Model\UrlRewriteFactory;
use Magento\UrlRewrite\Service\V1\Data\UrlRewrite;

require getcwd() . '/app/bootstrap.php';
$objectManager = Bootstrap::create(BP, $_SERVER)->getObjectManager();
$objectManager->get(State::class)->setAreaCode('adminhtml');

$storeId = (int)$objectManager->get(StoreManagerInterface::class)->getDefaultStoreView()->getId();
$finder = $objectManager->get(UrlFinderInterface::class);
$category = $finder->findOneByData([
    UrlRewrite::ENTITY_TYPE => 'category',
    UrlRewrite::STORE_ID => $storeId,
    UrlRewrite::REDIRECT_TYPE => 0,
]);
if ($category === null) {
    fwrite(STDERR, "The default store view has no category rewrite\n");
    exit(1);
}

$rewrites = [
    'gc-parity-redirect.html' => [$category->getRequestPath(), 301],
    'gc-parité.html' => [$category->getTargetPath(), 0],
];
foreach ($rewrites as $requestPath => [$targetPath, $redirectType]) {
    if ($finder->findOneByData([UrlRewrite::REQUEST_PATH => $requestPath, UrlRewrite::STORE_ID => $storeId])) {
        echo "$requestPath exists\n";
        continue;
    }
    $rewrite = $objectManager->get(UrlRewriteFactory::class)->create()
        ->setEntityType('custom')
        ->setEntityId(0)
        ->setRequestPath($requestPath)
        ->setTargetPath($targetPath)
        ->setRedirectType($redirectType)
        ->setStoreId($storeId)
        ->setIsAutogenerated(0)
        ->setDescription('Catalog storefront parity');
    $objectManager->get(UrlRewriteResource::class)->save($rewrite);
    echo "$requestPath -> $targetPath ($redirectType)\n";
}
